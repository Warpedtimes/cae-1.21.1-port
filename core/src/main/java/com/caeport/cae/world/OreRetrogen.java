import net.neoforged.fml.common.EventBusSubscriber;
import net.neoforged.neoforge.attachment.AttachmentType;
import net.neoforged.neoforge.event.level.ChunkEvent;
import net.neoforged.neoforge.event.level.LevelEvent;
import net.neoforged.neoforge.event.server.ServerStoppedEvent;
import net.neoforged.neoforge.event.tick.ServerTickEvent;
import net.neoforged.neoforge.registries.DeferredHolder;

/**
 * Silver and nickel ore for chunks made before 1.1.0, when the pack's {@code cae:silver_ore} / {@code cae:nickel_ore}
 * features did not exist. A chunk that loads without the marker {@code cae:ore_retrogen} is looked at once:
 * <ul>
 * <li>freshly generated by this session: worldgen ran the features already, so it is only marked;</li>
 * <li>already holds any silver or nickel ore (made with 1.1.0 or later, or retrogenned): only marked;</li>
 * <li>no overworld-style biome with the ore features in it (Nether, End, void dimensions): only marked;</li>
 * <li>otherwise the two placed features run once over the chunk, as worldgen would, then it is marked.</li>
 * </ul>
 * Cheap: the check reads the section palettes only, and the work happens on the server tick, a couple of chunks per tick,
 * once the chunk's eight neighbours are loaded (the veins reach over the border and must not load chunks).
 */
@EventBusSubscriber(modid = Cae.ID)
public final class OreRetrogen {
    private static final List<String> FEATURES = List.of("cae:silver_ore", "cae:nickel_ore");
    private static final List<String> ORES = List.of("cae:silver_ore", "cae:deepslate_silver_ore", "cae:nickel_ore", "cae:deepslate_nickel_ore");
    private static final int CHECKS_PER_TICK = 48;
    private static final int PLACEMENTS_PER_TICK = 2;
    private static final int RETRY_TICKS = 100;
    private static final int MAX_QUEUE = 30000;

    public static final DeferredHolder<AttachmentType<?>, AttachmentType<Boolean>> MARKER = CaeProperties.ATTACHMENTS.register(
            "ore_retrogen", () -> AttachmentType.builder(() -> Boolean.TRUE).serialize(Codec.BOOL).build());

    private static final class Pending {
        final ConcurrentLinkedQueue<Long> incoming = new ConcurrentLinkedQueue<>();
        final ArrayDeque<Long> queue = new ArrayDeque<>();
        final LongOpenHashSet queued = new LongOpenHashSet();
        final LongArrayList waiting = new LongArrayList();
        int sinceRetry;
    }

    private static final Map<ResourceKey<Level>, Pending> PENDING = new java.util.concurrent.ConcurrentHashMap<>();
    private static List<Block> oreBlocks;

    private OreRetrogen() {
    }

    /** Touching the class registers the marker attachment before the registries open. */
    public static void init() {
    }

    @SubscribeEvent
    public static void onChunkLoad(ChunkEvent.Load event) {
        if (!(event.getLevel() instanceof ServerLevel level) || !(event.getChunk() instanceof LevelChunk chunk)) {
            return;
        }
        if (chunk.hasData(MARKER)) {
            return;
        }
        if (event.isNewChunk()) {
            mark(chunk);
            return;
        }
        // the rest is decided on the server tick
        queue(level, chunk.getPos());
    }

    /** Looks at the chunk on a coming server tick, as if it had just loaded without the marker. */
    public static void queue(ServerLevel level, ChunkPos pos) {
        PENDING.computeIfAbsent(level.dimension(), k -> new Pending()).incoming.add(pos.toLong());
    }

    /** For tests: has the chunk been looked at? */
    public static boolean isMarked(LevelChunk chunk) {
        return chunk.hasData(MARKER);
    }

    /** For tests: forget that the chunk was looked at. */
    public static void clearMarker(LevelChunk chunk) {
        chunk.removeData(MARKER);
    }

    @SubscribeEvent
    public static void onTick(ServerTickEvent.Post event) {
        if (PENDING.isEmpty()) {
            return;
        }
        for (ServerLevel level : event.getServer().getAllLevels()) {
            Pending pending;
            {
                pending = PENDING.get(level.dimension());
            }
            if (pending != null) {
                process(level, pending);
            }
        }
    }

    @SubscribeEvent
    public static void onLevelUnload(LevelEvent.Unload event) {
        if (event.getLevel() instanceof Level level) {
            {
                PENDING.remove(level.dimension());
            }
        }
    }

    @SubscribeEvent
    public static void onServerStopped(ServerStoppedEvent event) {
        {
            PENDING.clear();
        }
        oreBlocks = null;
    }

    private static void process(ServerLevel level, Pending p) {
        Long in;
        while ((in = p.incoming.poll()) != null) {
            if (p.queue.size() < MAX_QUEUE && p.queued.add(in.longValue())) {
                p.queue.add(in);
            }
        }
        if (++p.sinceRetry >= RETRY_TICKS && !p.waiting.isEmpty()) {
            p.sinceRetry = 0;
            for (long l : p.waiting) {
                p.queue.add(l);
            }
            p.waiting.clear();
        }
        if (p.queue.isEmpty()) {
            return;
        }
        List<Block> ores = ores();
        Registry<PlacedFeature> registry = level.registryAccess().registryOrThrow(Registries.PLACED_FEATURE);
        List<PlacedFeature> features = new java.util.ArrayList<>();
        for (String id : FEATURES) {
            PlacedFeature f = registry.get(ResourceLocation.parse(id));
            if (f != null) {
                features.add(f);
            }
        }
        int checks = CHECKS_PER_TICK;
        int placements = PLACEMENTS_PER_TICK;
        while (checks-- > 0 && !p.queue.isEmpty() && placements > 0) {
            long key = p.queue.poll();
            ChunkPos pos = new ChunkPos(key);
            LevelChunk chunk = level.getChunkSource().getChunkNow(pos.x, pos.z);
            if (chunk == null || chunk.hasData(MARKER)) {
                p.queued.remove(key);
                continue;
            }
            if (ores.isEmpty() || features.size() != FEATURES.size() || hasOre(chunk, ores) || !hasFeatureBiome(chunk, features)) {
                mark(chunk);
                p.queued.remove(key);
                continue;
            }
            if (!neighboursLoaded(level, pos)) {
                p.waiting.add(key);
                p.queued.remove(key);
                continue;
            }
            place(level, chunk, features);
            mark(chunk);
            p.queued.remove(key);
            placements--;
        }
    }

    private static void place(ServerLevel level, LevelChunk chunk, List<PlacedFeature> features) {
        ChunkPos pos = chunk.getPos();
        BlockPos origin = new BlockPos(pos.getMinBlockX(), level.getMinBuildHeight(), pos.getMinBlockZ());
        WorldgenRandom random = new WorldgenRandom(new XoroshiroRandomSource(level.getSeed() ^ pos.toLong() * 0x9E3779B97F4A7C15L));
        for (PlacedFeature feature : features) {
            // with the biome check, as worldgen places them: the features end in minecraft:biome, which throws without it
            feature.placeWithBiomeCheck(level, level.getChunkSource().getGenerator(), random, origin);
        }
        // OreFeature writes straight into the sections (no block updates): save every chunk a vein can reach into and
        // send them again to the players who already have them
        for (int dx = -1; dx <= 1; dx++) {
            for (int dz = -1; dz <= 1; dz++) {
                LevelChunk c = level.getChunkSource().getChunkNow(pos.x + dx, pos.z + dz);
                if (c == null) {
                    continue;
                }
                c.setUnsaved(true);
                List<ServerPlayer> players = level.getChunkSource().chunkMap.getPlayers(c.getPos(), false);
                if (!players.isEmpty()) {
                    ClientboundLevelChunkWithLightPacket packet = new ClientboundLevelChunkWithLightPacket(c, level.getLightEngine(), null, null);
                    for (ServerPlayer player : players) {
                        player.connection.send(packet);
                    }
                }
            }
        }
    }

    private static void mark(ChunkAccess chunk) {
        chunk.setData(MARKER, Boolean.TRUE);
        chunk.setUnsaved(true);
    }

    private static boolean neighboursLoaded(ServerLevel level, ChunkPos pos) {
        for (int dx = -1; dx <= 1; dx++) {
            for (int dz = -1; dz <= 1; dz++) {
                if ((dx != 0 || dz != 0) && level.getChunkSource().getChunkNow(pos.x + dx, pos.z + dz) == null) {
                    return false;
                }
            }
        }
        return true;
    }

    private static boolean hasOre(LevelChunk chunk, List<Block> ores) {
        for (LevelChunkSection section : chunk.getSections()) {
            if (!section.hasOnlyAir() && section.maybeHas((BlockState s) -> ores.contains(s.getBlock()))) {
                // a palette keeps an entry after its last block is gone, so count the blocks of the (rare) hit
                boolean[] found = {false};
                section.getStates().count((state, n) -> {
                    if (n > 0 && ores.contains(state.getBlock())) {
                        found[0] = true;
                    }
                });
                if (found[0]) {
                    return true;
                }
            }
        }
        return false;
    }

    /** Is any biome of the chunk one the ore features were added to (the pack's biome modifiers: #minecraft:is_overworld)? */
    private static boolean hasFeatureBiome(LevelChunk chunk, List<PlacedFeature> features) {
        for (LevelChunkSection section : chunk.getSections()) {
            if (section.getBiomes().maybeHas(h -> {
                for (PlacedFeature f : features) {
                    if (h.value().getGenerationSettings().hasFeature(f)) {
                        return true;
                    }
                }
                return false;
            })) {
                return true;
            }
        }
        return false;
    }

    private static List<Block> ores() {
        if (oreBlocks == null) {
            java.util.ArrayList<Block> list = new java.util.ArrayList<>();
            for (String id : ORES) {
                BuiltInRegistries.BLOCK.getOptional(ResourceLocation.parse(id)).ifPresent(list::add);
            }
            oreBlocks = list.size() == ORES.size() ? list : List.of();
        }
        return oreBlocks;
    }
}
