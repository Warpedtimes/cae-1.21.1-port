// 1211: three Tinkers' Construct tanks of the 1.18.2 end-game rooms (Tinkers' Construct is not in the 1.21.1 pack), rebuilt as
// KubeJS blocks under their 1.18.2 ids with a real fluid tank (Create pumps / pipes / buckets work on it):
//   tconstruct:scorched_fuel_tank  egg room, 4000 mB cae:refined_fuel        (TankType.FUEL_TANK, 4000)
//   tconstruct:scorched_ingot_tank egg room, 4320 mB kubejs:soul_essence      (TankType.INGOT_TANK, 48 ingots x 90 = 4320)
//   tconstruct:seared_fuel_tank    insanity room, 4000 mB cae:refined_fuel
// The `level` property (0..8) only shows the fluid height: server_scripts/restoredTanks.js sets it from the tank. The models
// and textures are generated by tools/restore_tanks.py (Tinkers 3.6.4 look; the fluid is a pre-tinted texture, since a KubeJS
// block has no tint). The tank block entity type gets the block's id; the saved NBT is {attachments: {tank: <FluidStack>}}.
// Each id is spelled out in its own create() call on purpose (a tool scans for the literal ids).

StartupEvents.registry('block', event => {
    const IntegerProperty = Java.loadClass('net.minecraft.world.level.block.state.properties.IntegerProperty')
    const level = IntegerProperty.create('level', 0, 8)

    // Tinkers: seared tanks strength 3.0 / resistance 3000 (stone-ish), here pickaxe-only like the rest of the pack's machines
    event.create('tconstruct:scorched_fuel_tank')
        .displayName('Scorched Fuel Tank')
        .property(level)
        .defaultState(s => s.set(level, 0))
        .hardness(3.0).resistance(6.0).requiresTool(true).soundType('stone')
        .notSolid().renderType('translucent')
        .tagBlock('minecraft:mineable/pickaxe')
        .blockEntity(info => {
            info.serverTicking()
            info.tickFrequency(10)
            info.fluidTank('tank', [], 4000)
            info.rightClickFillsTank('tank')
        })

    event.create('tconstruct:scorched_ingot_tank')
        .displayName('Scorched Ingot Tank')
        .property(level)
        .defaultState(s => s.set(level, 0))
        .hardness(3.0).resistance(6.0).requiresTool(true).soundType('stone')
        .notSolid().renderType('translucent')
        .tagBlock('minecraft:mineable/pickaxe')
        .blockEntity(info => {
            info.serverTicking()
            info.tickFrequency(10)
            info.fluidTank('tank', [], 4320)
            info.rightClickFillsTank('tank')
        })

    event.create('tconstruct:seared_fuel_tank')
        .displayName('Seared Fuel Tank')
        .property(level)
        .defaultState(s => s.set(level, 0))
        .hardness(3.0).resistance(6.0).requiresTool(true).soundType('stone')
        .notSolid().renderType('translucent')
        .tagBlock('minecraft:mineable/pickaxe')
        .blockEntity(info => {
            info.serverTicking()
            info.tickFrequency(10)
            info.fluidTank('tank', [], 4000)
            info.rightClickFillsTank('tank')
        })
})
