const CAE_RST_LADDER_BOX = [0, 0, 13, 16, 16, 16] // vanilla LadderBlock's NORTH shape (attached to the block south of it)

function caeRstBlocks() { return Java.loadClass('net.minecraft.world.level.block.Blocks') }

// the vanilla Block of 'minecraft:x' (Blocks.X); vanilla blocks exist before any registry event
function caeRstBase(id) {
    let b = caeRstBlocks()[String(id).split(':')[1].toUpperCase()]
    if (b == null) { throw new Error('no vanilla block ' + id) }
    return b
}

StartupEvents.registry('block', event => {
    let Props = Java.loadClass('net.minecraft.world.level.block.state.BlockBehaviour$Properties')
    let DyeColor = Java.loadClass('net.minecraft.world.item.DyeColor')
    let BlockSetType = Java.loadClass('net.minecraft.world.level.block.state.properties.BlockSetType')
    let SlabType = Java.loadClass('net.minecraft.world.level.block.state.properties.BlockStateProperties').SLAB_TYPE
    CAE_RESTORED.forEach(r => {
        try {
            let id = r[0]
            let type = r[1]
            // a log's map colour reads its axis, which only pillars have: copying a log into anything else crashes the
            // block state setup (Dave's log piles are 'decor'), so those take the planks of the same wood
            let baseId = String(r[2])
            if (type != 'pillar' && /_(log|wood|stem|hyphae)$/.test(baseId)) {
                baseId = baseId.replace('stripped_', '').replace(/_(log|wood|stem|hyphae)$/, '_planks')
            }
            let base = caeRstBase(baseId)
            let render = r[4]
            let extra = r[5] || {}
            if (type == 'pane') {
                let PaneBlock = Java.loadClass('net.minecraft.world.level.block.StainedGlassPaneBlock')
                let color = DyeColor.byName(extra.color || 'white', DyeColor.WHITE)
                event.createCustom(id, () => new PaneBlock(color, Props.ofFullCopy(base)))
                return
            }
            if (type == 'chain') {
                let ChainBlock = Java.loadClass('net.minecraft.world.level.block.ChainBlock')
                event.createCustom(id, () => new ChainBlock(Props.ofFullCopy(base)))
                return
            }
            let kind = CAE_RST_TYPES[type]
            let b = kind ? event.create(id, kind) : event.create(id)
            b.displayName(r[3])
            b.copyPropertiesFrom(base)
            b.hardness(base.defaultDestroyTime())
            b.resistance(base.getExplosionResistance())
            if (render != 'solid') {
                b.notSolid()
                b.renderType(render)
            }
            if (type == 'glass' || type == 'tc_glass') { b.transparent(true) }
            if (type == 'plant' || type == 'decor' || type == 'decor_block') {
                b.noCollision()
                b.notSolid()
            }
            if (type == 'ladder') { b.box(CAE_RST_LADDER_BOX[0], CAE_RST_LADDER_BOX[1], CAE_RST_LADDER_BOX[2], CAE_RST_LADDER_BOX[3], CAE_RST_LADDER_BOX[4], CAE_RST_LADDER_BOX[5]) }
            if (type == 'vslab') {
                let box = extra.box || [0, 0, 0, 16, 16, 8]
                b.property(SlabType)
                b.defaultState(s => s.set(SlabType, 'bottom'))
                b.box(box[0], box[1], box[2], box[3], box[4], box[5])
            }
            if ((type == 'door' || type == 'trapdoor') && String(r[2]).indexOf('iron') >= 0) { b.behaviour(BlockSetType.IRON) }
            if (extra.tint) { b.color(0, extra.tint) }
        } catch (err) {
            console.warn('restoredBlocks.js: ' + r[0] + ' not registered: ' + err)
        }
    })
})

// block items for the createCustom blocks (KubeJS builders make their own)
StartupEvents.registry('item', event => {
    let BlockItem = Java.loadClass('net.minecraft.world.item.BlockItem')
    let ItemProps = Java.loadClass('net.minecraft.world.item.Item$Properties')
    let Registry = Java.loadClass('net.minecraft.core.registries.BuiltInRegistries')
    let RL = Java.loadClass('net.minecraft.resources.ResourceLocation')
    CAE_RESTORED.forEach(r => {
        if (r[1] != 'pane' && r[1] != 'chain') { return }
        try {
            let id = r[0]
            event.createCustom(id, () => new BlockItem(Registry.BLOCK.getOptional(RL.parse(id)).get(), new ItemProps()))
        } catch (err) {
            console.warn('restoredBlocks.js: item ' + r[0] + ' not registered: ' + err)
        }
    })
})
